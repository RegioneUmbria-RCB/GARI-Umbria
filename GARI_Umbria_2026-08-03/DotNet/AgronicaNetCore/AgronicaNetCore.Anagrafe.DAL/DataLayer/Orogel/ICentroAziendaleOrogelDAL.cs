using System.Data;
using AgronicaNetCore.Base.Models;

namespace AgronicaNetCore.Anagrafe.DAL.DataLayer.Orogel
{
    /// <summary>
    /// DS06-BL §Persistenze: Data access contract for paginated extraction of centro aziendale
    /// data from <c>Centri_Aziendali</c> with geographical LEFT JOINs.
    /// </summary>
    public interface ICentroAziendaleOrogelDAL
    {
        /// <summary>
        /// DS06-BL §Query base / Filtri / Paginazione: Executes
        /// <c>SELECT TOP(@pageSize) … FROM Centri_Aziendali ca LEFT JOIN … ORDER BY ca.PIVA ASC, ca.sa_cod ASC</c>
        /// applying temporal validity filters, an optional company code filter and the
        /// 2-key keyset pagination WHERE fragment generated by DS04-BL.
        /// </summary>
        /// <param name="pageSize">Number of rows to fetch (<c>TOP</c> argument).</param>
        /// <param name="parSqlPaginazione">
        /// Keyset SQL parameters from DS04-BL (<c>@LastPiva</c>, <c>@LastSaCod</c>).
        /// The 2-key keyset WHERE fragment is built internally using table-qualified column references
        /// to avoid ambiguity across the multi-table LEFT JOIN.
        /// </param>
        /// <param name="codiciAzienda">Optional PIVA filter list. Empty list → no filter.</param>
        /// <param name="objParametriServer">Connection parameters for the target archive database.</param>
        /// <returns>
        /// A <see cref="DataTable"/> with columns matching the DS06-BL output fields:
        /// <c>codice_azienda</c>, <c>codice_centro</c>, <c>data_inizio</c>, <c>data_fine</c>,
        /// <c>destinazione_prodotto</c>, <c>indirizzo</c>, <c>frazione</c>, <c>cap</c>,
        /// <c>localita</c>, <c>provincia</c>, <c>codice_istat</c>.
        /// </returns>
        Task<DataTable> LeggiCentriAziendaliPaginatiAsync(
            int pageSize,
            IReadOnlyDictionary<string, object> parSqlPaginazione,
            IReadOnlyList<string> codiciAzienda,
            AgronicaCoreParametriServer objParametriServer);
    }
}
