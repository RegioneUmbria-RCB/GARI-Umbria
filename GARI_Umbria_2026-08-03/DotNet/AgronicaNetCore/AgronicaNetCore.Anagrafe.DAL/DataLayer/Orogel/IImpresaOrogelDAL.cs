using System.Data;
using AgronicaNetCore.Base.Models;

namespace AgronicaNetCore.Anagrafe.DAL.DataLayer.Orogel
{
    /// <summary>
    /// DS05-BL §Persistenze: Data access contract for paginated extraction of company
    /// anagrafica from the <c>Imprese</c> table in the target archive database.
    /// </summary>
    public interface IImpresaOrogelDAL
    {
        /// <summary>
        /// DS05-BL §Query base / Filtri / Paginazione: Executes
        /// <c>SELECT TOP(@pageSize) … FROM Imprese WHERE … ORDER BY PIVA ASC</c>
        /// applying temporal validity filters, an optional company code filter
        /// and the keyset pagination WHERE fragment generated by DS04-BL.
        /// </summary>
        /// <param name="pageSize">Number of rows to fetch (<c>TOP</c> argument).</param>
        /// <param name="filtroWherePaginazione">
        /// Keyset WHERE fragment built by <c>IOrogelPaginazioneKeysetService.DecodificaNextKey</c>
        /// (e.g. <c>PIVA &gt; @LastPiva</c>). Always non-null.
        /// </param>
        /// <param name="parSqlPaginazione">
        /// Bound SQL parameters for <paramref name="filtroWherePaginazione"/>
        /// (e.g. <c>@LastPiva → ""</c> for first page).
        /// </param>
        /// <param name="codiciAzienda">
        /// Optional PIVA filter list. Empty list means no filter (all companies returned).
        /// </param>
        /// <param name="objParametriServer">Connection parameters for the target archive database.</param>
        /// <returns>
        /// A <see cref="DataTable"/> with columns <c>codice_azienda</c>, <c>ragione_sociale</c>,
        /// <c>data_inizio</c>, <c>data_fine</c>.
        /// </returns>
        Task<DataTable> LeggiImpresePaginateAsync(
            int pageSize,
            string filtroWherePaginazione,
            IReadOnlyDictionary<string, object> parSqlPaginazione,
            IReadOnlyList<string> codiciAzienda,
            AgronicaCoreParametriServer objParametriServer);
    }
}
