    public isImpiantoEdited(index: number): boolean {
        const impianto = this.dialogImpianti[index];
        const original = this.originalDialogImpianti[index];
        if (!impianto || !original) return false;
        if (this.impiantiGridColumns) {
            const isEdited = this.impiantiGridColumns.some((col: any) => {
                if (!col.editable) return false;
                const a = impianto[col.field];
                const b = original[col.field];
                const empty = (v: any) => v === undefined || v === null || v === '';
                if (empty(a) && empty(b)) return false;

                // Check if this is a date field (any field containing 'data' or 'date')
                const isDateField = col.field && (col.field.toLowerCase().includes('data') || col.field.toLowerCase().includes('date'));
                if (isDateField) {
                    const dateA = (a instanceof Date) ? a : (typeof a === 'string' && !empty(a) ? new Date(a) : null);
                    const dateB = (b instanceof Date) ? b : (typeof b === 'string' && !empty(b) ? new Date(b) : null);

                    // If both are null/invalid, they're the same
                    if (!dateA && !dateB) return false;

                    // If one is null and the other isn't, they're different
                    if (!dateA || !dateB) return true;

                    // If both are valid dates, compare them
                    if (dateA instanceof Date && !isNaN(dateA.getTime()) &&
                        dateB instanceof Date && !isNaN(dateB.getTime())) {
                        return dateA.getTime() !== dateB.getTime();
                    }

                    // Fallback to string comparison for invalid dates
                    return String(a) !== String(b);
                }
                return a !== b;
            });
            if (isEdited) {
                this.hasImpiantiEdits = true;
            }

            return isEdited;
        }
        this.hasImpiantiEdits = false;
        return false;
    }

    public resetImpiantoEdit(index: number): void {

        if (this.selectedImpianto && index === this.selectedImpiantoIndex && this.originalDialogImpianti[index]) {
            if (this.impiantiGridColumns) {
                this.impiantiGridColumns.forEach((col: any) => {
                    if (col.editable && this.selectedImpianto[col.field] !== this.originalDialogImpianti[index][col.field]) {
                        this.selectedImpianto[col.field] = this.originalDialogImpianti[index][col.field];
                    }
                });
            }
        } else if (this.originalDialogImpianti[index] && this.dialogImpianti[index]) {
            // Fallback: reset only the edited fields in the array item
            if (this.impiantiGridColumns) {
                this.impiantiGridColumns.forEach((col: any) => {
                    if (col.editable && this.dialogImpianti[index][col.field] !== this.originalDialogImpianti[index][col.field]) {
                        this.dialogImpianti[index][col.field] = this.originalDialogImpianti[index][col.field];
                    }
                });
            }
        }
    }

