    public getSuperficieTrattataErrorMessage(impianto?: any): string {
        const targetImpianto = impianto || this.selectedImpianto;
        if (!targetImpianto) return '';

        const supTotale = parseFloat(targetImpianto.Sup_Imp);
        const supRiduzione = parseFloat(targetImpianto.Sup_Riduzione_BufferZone) || 0;
        const maxSupTrattata = supTotale - supRiduzione;

        return this.translocoService.translate('GridImpianti_SuperficieTrattataMaxError', { max: maxSupTrattata.toFixed(4) });
    }

    private validateAllChanges(): boolean {
        let isValid = true;

        // Validate each impianto in the dialog
        for (let i = 0; i < this.dialogImpianti.length; i++) {
            const impianto = this.dialogImpianti[i];

            // Check if Sup_Imp_help field needs validation
            if (impianto.Sup_Imp_help !== undefined && impianto.Sup_Imp_help !== null) {
                if (!this.validateSuperficieTrattataForImpianto(impianto)) {
                    isValid = false;
                    // Show error message for this specific impianto
                    const errorMessage = this.getSuperficieTrattataErrorMessage(impianto);
                    this.notificationService.show({
                        content: `${impianto.rag_soc} - ${impianto.APP_NOME}: ${errorMessage}`,
                        type: { style: 'error', icon: true },
                        position: { horizontal: 'center', vertical: 'top' },
                        animation: { type: 'fade', duration: 400 },
                        hideAfter: 6000
                    });
                }
            }

            // Validate DataFineIrrigazione is not earlier than DataInizioIrrigazione
            if (impianto.DataInizioIrrigazione && impianto.DataFineIrrigazione) {
                const startDate = impianto.DataInizioIrrigazione instanceof Date ?
                    impianto.DataInizioIrrigazione :
                    (typeof impianto.DataInizioIrrigazione === 'string' && impianto.DataInizioIrrigazione ?
                        new Date(impianto.DataInizioIrrigazione) : null);
                const endDate = impianto.DataFineIrrigazione instanceof Date ?
                    impianto.DataFineIrrigazione :
                    (typeof impianto.DataFineIrrigazione === 'string' && impianto.DataFineIrrigazione ?
                    new Date(impianto.DataFineIrrigazione) : null);

                if (startDate instanceof Date && !isNaN(startDate.getTime()) &&
                    endDate instanceof Date && !isNaN(endDate.getTime())) {
                    if (endDate < startDate) {
                        isValid = false;
                        const msg = this.translocoService.translate('DataInizioNonDeveEssereMaggioreDiDataFine');
                        this.notificationService.show({
                            content: `${impianto.rag_soc} - ${impianto.APP_NOME}: ${msg}`,
                            type: { style: 'error', icon: true },
                            position: { horizontal: 'center', vertical: 'top' },
                            animation: { type: 'fade', duration: 400 },
                            hideAfter: 6000
                        });
                    }
                }
            }
        }

        return isValid;
    }

    private validateSuperficieTrattataForImpianto(impianto: any): boolean {
        if (!impianto.Sup_Imp_help || impianto.Sup_Imp_help <= 0) return true; // Skip validation for empty/zero values

        const supTotale = parseFloat(impianto.Sup_Imp);
        const supRiduzione = parseFloat(impianto.Sup_Riduzione_BufferZone);
        const supTrattata = parseFloat(impianto.Sup_Imp_help);
        const maxSupTrattata = supTotale - supRiduzione;

        return supTrattata <= maxSupTrattata;
    }

    // Validation method for superficie trattata
    validateSuperficieTrattata(value: any): boolean {
        if (!this.selectedImpianto || !value || value <= 0) return true;

        const supTrattata = parseFloat(value);
        const supTotale = parseFloat(this.selectedImpianto.SUP_APP);

        if (isNaN(supTrattata) || isNaN(supTotale)) return true;

        return supTrattata <= supTotale;
    }

    // Event handler for superficie trattata value change
    onSuperficieTrattataChange(value: any, field: string): void {
        if (!this.selectedImpianto) return;

        const supTrattata = parseFloat(value);
        const supTotale = parseFloat(this.selectedImpianto.SUP_APP);

        if (!isNaN(supTrattata) && !isNaN(supTotale) && supTrattata > supTotale) {
            // Reset to maximum allowed value
            this.selectedImpianto[field] = supTotale;

            // Show warning message
            this.notificationService.show({
                content: this.translocoService.translate('GridImpianti_SuperficieTrattataExceedsTotal', {
                    trattata: supTrattata.toFixed(2),
                    totale: supTotale.toFixed(2)
                }),
                type: { style: 'warning', icon: true },
                position: { horizontal: 'center', vertical: 'top' },
                animation: { type: 'fade', duration: 400 },
                hideAfter: 4000
            });
        } else {
            this.selectedImpianto[field] = value;
        }
    }

